/* Figure H1, "the card on the turntable". An RTX 4060 (the pool's last stage, layers 29–39 of Qwen3-14B)
   turns on a machined turntable in the Anatomy kit's 3D mode; its two fans spin, and on hover the cooler
   lifts off to show the die and the four memory chips round it, with a WebGL glow on the board.
   Self-contained: place it anywhere. The scene (stage markup and solved paint order) is generated by
   scripts/anatomy/gpu-hero.mjs and loaded lazily with the 3D runtime. */
import { useEffect, useRef } from "react";
import { Plate } from "./kit/react/draw";
import "./kit/iso.css";
import "./gpu/gpu-hero.css";
import { FAN_DEG_PER_S, REST_TURN, SHOW_TURN, TOUR_DEG_PER_S, follow, readoutOf } from "./gpu/model";

type Props = { theme?: "dark" | "light"; caption?: boolean; className?: string };

const LABEL = "The pool's RTX 4060 on a turntable. Hover, tap or press Space to lift the cooler; drag or use the arrow keys to turn it.";

export default function GpuHero({ theme = "dark", caption = true, className }: Props) {
  const stageRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const stage = stageRef.current;
    if (!stage) return;
    const live = { disposed: false, cleanup: () => {} };
    (async () => {
      const [{ default: data }, { TURN }, gl, { glowFragment }] = await Promise.all([import("./gpu/stage.gen.json"), import("./kit/turn.mjs"), import("./kit/gl.mjs"), import("./gpu/glow")]);
      if (live.disposed) return;
      const style = document.createElement("style");
      style.textContent = data.css;
      stage.innerHTML = data.stage;
      stage.prepend(style);
      live.cleanup = run(stage, data, TURN, gl, glowFragment);
      stage.setAttribute("data-ready", "");
    })().catch((error) => {
      // The still picture under the card is enough; the figure just does not move.
      console.error("gpu hero:", error);
    });
    return () => {
      live.disposed = true;
      live.cleanup();
    };
  }, []);

  return (
    <div className={`iso gh${className ? ` ${className}` : ""}`} data-theme={theme}>
      <Plate
        fig="Fig 1"
        title="The card on the turntable"
        hint="Hover to lift · drag to turn"
        readout={readoutOf(REST_TURN, 0)}
        caption={caption ? "One node of the pool: an RTX 4060 with 8 GB holds layers 29–39 of Qwen3-14B. Under the cooler, the die and its four 2 GB memory chips do the work; the fans are drawn slowed." : undefined}
      >
        <div ref={stageRef} className="iso-stage iso-turn gh-stage" tabIndex={0} role="slider" aria-label={LABEL} aria-valuemin={0} aria-valuemax={359} aria-valuenow={REST_TURN} aria-valuetext={`turned ${REST_TURN} degrees, cooler on`} />
      </Plate>
    </div>
  );
}

type Turn = typeof import("./kit/turn.mjs").TURN;
type Gl = typeof import("./kit/gl.mjs");
type Data = { W: number; H: number; gl: { camera: unknown; die: number[]; pcbZ: number }; turn: unknown };

/* The live part, imperative on purpose: one loop writes the DOM through the 3D runtime, React never re-renders. */
function run(stage: HTMLDivElement, data: Data, TURN: Turn, GL: Gl, glowFragment: (die: number[], pcbZ: number) => string) {
  const still = matchMedia("(prefers-reduced-motion: reduce)");
  const readout = stage.closest(".iso-plate")?.querySelector("[data-readout]");
  const light = stage.closest("[data-theme]")?.getAttribute("data-theme") === "light" ? 1 : 0;
  let turn = REST_TURN;
  let target = REST_TURN;
  let spin = 0;
  const lift = { x: 0, v: 0 };
  let lifted = 0;
  const on = { x: 0, v: 0 };
  let touring = !still.matches;
  let held = false;
  let lite = false;
  let visible = false;
  let frame = 0;
  let last = 0;
  let clock = 0;
  let idle = 0;
  let cost = 0;
  let skip = false;
  let own = false;

  const controller = TURN.mount(stage, data.turn, {
    follow,
    // A tool driving window.__isoTurn holds the figure still until the reader acts again.
    onHold: () => {
      touring = false;
      held = true;
      clearTimeout(idle);
      stop();
    },
    // A tool (or a test) that sets the figure through window.__isoTurn takes over the values.
    onFrame: (c) => {
      if (own) return;
      const v = c.values as Record<string, number>;
      turn = target = v.table ?? turn;
      if (typeof v.lift === "number") lift.x = lifted = v.lift;
    },
  });
  const canvas = stage.querySelector<HTMLCanvasElement>('[data-canvas="glow"]');
  const glow = canvas ? GL.glLayer({ canvas, fragment: glowFragment(data.gl.die, data.gl.pcbZ), view: [data.W, data.H], camera: data.gl.camera, uniforms: ["uOn", "uLoad", "uTableX", "uTableY", "uTableZ", "uTableT"], fixed: { uLight: light }, onError: () => {} }) : null;
  if (glow) stage.setAttribute("data-gl", "");

  const describe = () => {
    const deg = ((Math.round(target) % 360) + 360) % 360;
    stage.setAttribute("aria-valuenow", String(deg));
    stage.setAttribute("aria-valuetext", `turned ${deg} degrees, cooler ${lifted ? "lifted, die and memory chips showing" : "on"}`);
  };
  const say = () => {
    const text = readoutOf(turn, lift.x);
    if (readout && readout.textContent !== text) readout.textContent = text;
  };
  const draw = () => {
    const start = performance.now();
    own = true;
    controller.set({ table: turn, lift: lift.x, spin });
    own = false;
    if (glow) glow.draw({ uOn: on.x, uLoad: 0.86 + 0.14 * Math.sin(clock * 1.3), ...TURN.poseUniforms(controller, "table", "uTable") }, clock);
    const ms = performance.now() - start;
    cost = cost ? cost * 0.9 + ms * 0.1 : ms;
    say();
  };
  const hold = () => {
    held = false;
    touring = false;
    clearTimeout(idle);
    idle = window.setTimeout(() => {
      touring = !still.matches && !lifted && !lite;
      kick();
    }, 3600);
  };

  const tick = (now: number) => {
    const dt = last ? Math.min((now - last) / 1000, 1 / 30) : 1 / 60;
    last = now;
    const calm = still.matches;
    clock += dt;
    if (touring && !calm) target += TOUR_DEG_PER_S * dt;
    turn = calm ? target : turn + (target - turn) * (1 - Math.exp(-dt / 0.14));
    if (Math.abs(target - turn) < 1e-3) turn = target;
    if (!calm) spin = (spin + FAN_DEG_PER_S * dt) % 360;
    const lifting = GL.settle(lift, lifted, dt, 0.32, calm);
    const lighting = GL.settle(on, 1, dt, 0.6, calm);
    // Adaptive half rate: above 14 ms a frame, paint every other frame (time-based motion is unchanged).
    if (cost > 14) skip = !skip;
    else if (cost < 9) skip = false;
    if (!skip || calm) draw();
    // A slow device (a phone, measured: ~15 ms per turning frame at 4× CPU throttle) stops the idle tour after
    // a second of it. The fans keep spinning, which repaints only the rotors (~1/6 of the work); dragging still turns.
    if (touring && !lite && clock > 1 && cost > 8) {
      lite = true;
      touring = false;
      stage.setAttribute("data-lite", "");
    }
    const moving = !calm || lifting || lighting || turn !== target;
    frame = visible && !document.hidden && moving ? requestAnimationFrame(tick) : 0;
  };
  const kick = () => {
    if (!frame && visible && !document.hidden && !held) {
      last = 0;
      frame = requestAnimationFrame(tick);
    }
  };
  const stop = () => {
    cancelAnimationFrame(frame);
    frame = 0;
  };

  const seen = new IntersectionObserver((entries) => {
    visible = Boolean(entries.at(-1)?.isIntersecting);
    if (visible) kick();
    else stop();
  }, { rootMargin: "120px 0px" });
  seen.observe(stage);
  const onVisibility = () => (document.hidden ? stop() : kick());
  document.addEventListener("visibilitychange", onVisibility);

  const setLift = (value: number) => {
    if (lifted === value) return;
    lifted = value;
    // Lifting also eases the table to the nearest angle where the board lies across the view.
    if (value) target += ((((SHOW_TURN - target) % 180) + 270) % 180) - 90;
    describe();
    kick();
  };
  let drag: { from: number; base: number; id: number; moved: boolean } | null = null;
  const onEnter = (e: PointerEvent) => {
    if (e.pointerType === "mouse") {
      hold();
      setLift(1);
    }
  };
  const onLeave = (e: PointerEvent) => {
    if (e.pointerType === "mouse" && !drag) {
      hold();
      setLift(0);
    }
  };
  const onDown = (e: PointerEvent) => {
    hold();
    drag = { from: controller.angleAt(e.clientX, e.clientY, 6, "table"), base: target, id: e.pointerId, moved: false };
  };
  const onMove = (e: PointerEvent) => {
    if (!drag || e.pointerId !== drag.id) return;
    const delta = controller.angleAt(e.clientX, e.clientY, 6, "table") - drag.from;
    if (!drag.moved && Math.abs(delta) > 2) {
      drag.moved = true;
      stage.setPointerCapture(e.pointerId);
      stage.setAttribute("data-drag", "");
    }
    if (!drag.moved) return;
    hold();
    target = drag.base + delta;
    kick();
  };
  const onUp = (e: PointerEvent) => {
    if (!drag || e.pointerId !== drag.id) return;
    const tap = !drag.moved;
    drag = null;
    stage.removeAttribute("data-drag");
    if (stage.hasPointerCapture(e.pointerId)) stage.releasePointerCapture(e.pointerId);
    if (tap && e.pointerType !== "mouse") setLift(lifted ? 0 : 1);
    describe();
  };
  const onKey = (e: KeyboardEvent) => {
    let next: number | null = null;
    if (e.key === "ArrowRight" || e.key === "ArrowUp") next = target - (e.shiftKey ? 45 : 15);
    if (e.key === "ArrowLeft" || e.key === "ArrowDown") next = target + (e.shiftKey ? 45 : 15);
    if (e.key === "Home") next = REST_TURN;
    if (e.key === " " || e.key === "Enter") {
      e.preventDefault();
      hold();
      setLift(lifted ? 0 : 1);
      return;
    }
    if (e.key === "Escape") {
      setLift(0);
      return;
    }
    if (next === null) return;
    e.preventDefault();
    hold();
    target = next;
    describe();
    kick();
  };
  stage.addEventListener("pointerenter", onEnter);
  stage.addEventListener("pointerleave", onLeave);
  stage.addEventListener("pointerdown", onDown);
  stage.addEventListener("pointermove", onMove);
  stage.addEventListener("pointerup", onUp);
  stage.addEventListener("pointercancel", onUp);
  stage.addEventListener("keydown", onKey);
  const onStill = () => {
    touring = !still.matches;
    kick();
  };
  still.addEventListener("change", onStill);

  // First paint: the rest pose, and with reduced motion that is the only frame until the reader acts.
  if (still.matches) on.x = 1;
  draw();
  describe();

  return () => {
    stop();
    clearTimeout(idle);
    seen.disconnect();
    document.removeEventListener("visibilitychange", onVisibility);
    still.removeEventListener("change", onStill);
    stage.removeEventListener("pointerenter", onEnter);
    stage.removeEventListener("pointerleave", onLeave);
    stage.removeEventListener("pointerdown", onDown);
    stage.removeEventListener("pointermove", onMove);
    stage.removeEventListener("pointerup", onUp);
    stage.removeEventListener("pointercancel", onUp);
    stage.removeEventListener("keydown", onKey);
    controller.destroy();
  };
}
